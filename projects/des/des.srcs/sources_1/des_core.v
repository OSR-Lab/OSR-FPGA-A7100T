`timescale 1ns / 1ps
// ============================================================================
// DES Core - 64-bit Data Encryption Standard (FIPS 46-3)
// Iterative design: computes one subkey per round
// Protocol:
//   - Assert start for 1 clock with enc_dec, key_in, data_in valid
//   - busy goes high
//   - After 18 clocks, done pulses high for 1 cycle, data_out is valid
// ============================================================================
module des_core (
    input  wire        clk,
    input  wire        rst_n,
    input  wire        start,
    input  wire        enc_dec,    // 0 = encrypt, 1 = decrypt
    input  wire [63:0] key_in,
    input  wire [63:0] data_in,
    output reg  [63:0] data_out,
    output reg         done,
    output reg         busy
);

