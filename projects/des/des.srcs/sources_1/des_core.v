function [1:0] shift_amt; input [3:0] rnd; begin
    if (rnd == 4'd0 || rnd == 4'd1 || rnd == 4'd8 || rnd == 4'd15)
        shift_amt = 2'd1;
    else
        shift_amt = 2'd2;
end endfunction

// ---------------------------------------------------------------
// State machine registers
// ---------------------------------------------------------------
reg [4:0]  round;
reg [31:0] L, R;
reg [27:0] C, D;
reg        mode_r;

// ---------------------------------------------------------------
// Main FSM: iterative key schedule + Feistel rounds
// ---------------------------------------------------------------
(* keep = "true" *) // suppress optimization warnings for named-block locals
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        round    <= 5'd0;
        L        <= 32'd0;
        R        <= 32'd0;
        C        <= 28'd0;
        D        <= 28'd0;
        data_out <= 64'd0;
        done     <= 1'b0;
        busy     <= 1'b0;
        mode_r   <= 1'b0;
    end else begin
        done <= 1'b0;

        if (start && !busy) begin
            {L, R} <= initial_perm(data_in);
            begin : init_key
                reg [55:0] pc1_result;
                pc1_result = pc1(key_in);
                C <= pc1_result[55:28];
                D <= pc1_result[27:0];
            end
            mode_r <= enc_dec;
            round  <= 5'd1;
            busy   <= 1'b1;

        end else if (busy) begin
            if (round >= 5'd1 && round <= 5'd16) begin
                begin : key_compute
                    reg [27:0] Cn, Dn;
                    reg [47:0] rk;
                    reg [1:0]  sh;

                    if (!mode_r) begin
                        sh = shift_amt(round - 1);
                        if (sh == 2'd1) begin
                            Cn = {C[26:0], C[27]};
                            Dn = {D[26:0], D[27]};
                        end else begin
                            Cn = {C[25:0], C[27:26]};
                            Dn = {D[25:0], D[27:26]};
                        end
                        rk = pc2({Cn, Dn});
                        C <= Cn;
                        D <= Dn;
                    end else begin
                        rk = pc2({C, D});
                        sh = shift_amt(5'd16 - round);
                        if (sh == 2'd1) begin
                            Cn = {C[0], C[27:1]};
                            Dn = {D[0], D[27:1]};
                        end else begin
                            Cn = {C[1:0], C[27:2]};
                            Dn = {D[1:0], D[27:2]};
                        end
                        C <= Cn;
                        D <= Dn;
                    end

                    L <= R;
                    R <= L ^ feistel_f(R, rk);
                end
                round <= round + 1'b1;

            end else if (round == 5'd17) begin
                data_out <= final_perm({R, L});
                done     <= 1'b1;
                busy     <= 1'b0;
                round    <= 5'd0;
            end
        end
    end
end

